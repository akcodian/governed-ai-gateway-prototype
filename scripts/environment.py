"""Write results/environment.md: hardware, OS, Python, Docker, image digests, package and convention versions."""
from __future__ import annotations

import ctypes
import json
import os
import platform
import subprocess
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

TABLE2_GENAI = ["gen_ai.operation.name", "gen_ai.request.model", "gen_ai.response.model", "gen_ai.usage.input_tokens",
                "gen_ai.usage.output_tokens"]


def run(cmd: list[str]) -> str:
    try:
        return subprocess.run(cmd, capture_output=True, text=True, cwd=ROOT, timeout=60).stdout.strip()
    except (OSError, subprocess.TimeoutExpired):
        return "unavailable"


def cpu() -> str:
    if platform.system() == "Windows":
        out = run(["powershell", "-NoProfile", "-Command",
                   "(Get-CimInstance Win32_Processor | Select-Object -First 1).Name"])
        return out or platform.processor()
    if Path("/proc/cpuinfo").exists():
        for line in Path("/proc/cpuinfo").read_text().splitlines():
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    return platform.processor()


def ram_gb() -> str:
    if platform.system() == "Windows":
        class MEM(ctypes.Structure):
            _fields_ = [("dwLength", ctypes.c_ulong), ("dwMemoryLoad", ctypes.c_ulong), ("ullTotalPhys", ctypes.c_ulonglong),
                        ("ullAvailPhys", ctypes.c_ulonglong), ("ullTotalPageFile", ctypes.c_ulonglong),
                        ("ullAvailPageFile", ctypes.c_ulonglong), ("ullTotalVirtual", ctypes.c_ulonglong),
                        ("ullAvailVirtual", ctypes.c_ulonglong), ("sullAvailExtendedVirtual", ctypes.c_ulonglong)]
        m = MEM()
        m.dwLength = ctypes.sizeof(MEM)
        ctypes.windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(m))
        return f"{m.ullTotalPhys / 2**30:.1f}"
    if Path("/proc/meminfo").exists():
        kb = int(Path("/proc/meminfo").read_text().split()[1])
        return f"{kb / 2**20:.1f}"
    return "unknown"


def host_lines() -> list[str]:
    return [f"- CPU: {cpu()} ({os.cpu_count()} logical cores)", f"- RAM: {ram_gb()} GB",
            f"- OS: {platform.platform()}"]


def images() -> list[tuple[str, str]]:
    ids = run(["docker", "compose", "ps", "-q"]).split()
    out = []
    for cid in ids:
        info = run(["docker", "inspect", "--format", "{{.Name}}|{{.Config.Image}}|{{.Image}}", cid])
        if "|" in info:
            name, image, digest = info.split("|")
            out.append((name.strip("/"), f"{image} (local image id {digest[:19]})"))
    return sorted(out)


def main() -> None:
    from govlib.telemetry import SEMCONV_SCHEMA_URL
    from opentelemetry.semconv._incubating.attributes import gen_ai_attributes as g

    pinned = {v for k, v in vars(g).items() if k.startswith("GEN_AI_") and isinstance(v, str)}
    diffs = [a for a in TABLE2_GENAI if a not in pinned]
    native = os.environ.get("STACK_MODE") == "native"
    opa = Path(os.environ["OPA_BIN"]) if os.environ.get("OPA_BIN") else         ROOT / ".tools" / ("opa.exe" if platform.system() == "Windows" else "opa")
    opa_ver = (run([str(opa), "version"]).splitlines() or ["unavailable"])[0] if opa.exists() else "not installed"
    if native:
        redis_ver = run([os.environ.get("REDIS_SERVER", "redis-server"), "--version"])
        otel_ver = run([os.environ.get("OTELCOL_BIN", "otelcol-contrib"), "--version"])
        runtime_lines = [
            "- Services run as local processes in one container (STACK_MODE=native, scripts/native_stack.py)",
            f"- Service Python: {platform.python_version()} (same interpreter as the tests)",
            f"- OPA (server and CLI): {opa_ver}",
            f"- Redis: {redis_ver}",
            f"- OpenTelemetry Collector: {otel_ver}", "",
        ]
        image_lines = []
    else:
        docker_ver = run(["docker", "version", "--format", "client {{.Client.Version}} / server {{.Server.Version}}"])
        compose_ver = run(["docker", "compose", "version", "--short"])
        runtime_lines = [
            "- Service Python (containers): 3.12.16 (python:3.12.16-slim-bookworm)",
            f"- Docker: {docker_ver}; Compose {compose_ver}",
            f"- OPA CLI (compile/test): {opa_ver}", "",
        ]
        image_lines = ["## Container images (docker-compose.yml pins tag + digest)", "",
                       "| container | image |", "|---|---|", *[f"| {n} | `{i}` |" for n, i in images()], ""]
    pkgs = ["fastapi", "uvicorn", "httpx", "pydantic", "redis", "PyJWT", "cryptography", "mcp", "a2a-sdk",
            "opentelemetry-sdk", "opentelemetry-exporter-otlp-proto-http", "opentelemetry-semantic-conventions",
            "duckdb", "pytest"]
    lines = [
        "# Environment", "",
        "Generated by `make env` (scripts/environment.py) on the machine that produced the results.", "",
        "## Hardware and OS", "",
        *(host_lines() if "--host-details" in sys.argv else [
            "- CPU: <CPU MODEL, LOGICAL CORES>",
            "- RAM: <RAM GB>",
            "- OS: <OS AND VERSION>",
            "- (Host hardware redacted by default; run `python scripts/environment.py --host-details` to record it.)",
        ]),
        f"- Host Python (tests, benchmark client): {platform.python_version()}",
        *runtime_lines,
        *image_lines,
        "## Python packages (exact pins in requirements.lock)", "",
        *[f"- {p} {metadata.version(p)}" for p in pkgs], "",
        "## Protocol and convention versions", "",
        f"- OpenTelemetry semantic conventions: schema {SEMCONV_SCHEMA_URL} "
        f"(opentelemetry-semantic-conventions {metadata.version('opentelemetry-semantic-conventions')})",
        "- MCP: official Python SDK `mcp` " + metadata.version("mcp") + " (MCPServer, streamable HTTP, stateless JSON)",
        "- A2A: protocol 1.0, JSON-RPC binding; Agent Card at `/.well-known/agent-card.json`; method `SendMessage` "
        f"(checked against a2a-sdk {metadata.version('a2a-sdk')}; cards validated with its protobuf AgentCard)", "",
        "## Attribute names vs. the paper's Table 2", "",
        "GenAI attributes used: " + ", ".join(f"`{a}`" for a in TABLE2_GENAI) + ".",
        ("All match the pinned convention." if not diffs else
         "Differences (convention name kept): " + ", ".join(diffs)),
        "Additional convention attributes emitted: `gen_ai.provider.name`, `gen_ai.tool.name`, `gen_ai.agent.name`.",
        "Governance attributes use the enterprise `gov.` namespace as listed in SPEC.md section 6.1; additional `gov.` "
        "attributes emitted: `gov.decision.stage`, `gov.hold.id`, `gov.policy.would_deny`, `gov.budget.fail_mode`, "
        "`gov.route.skipped.<model>`, `gov.identity.header_mismatch`, `gov.a2a.hop`, `gov.guard.redactions.*`.",
        "Note: Table 2 itself was not available to the builder; the comparison uses the names listed in SPEC.md 6.1.",
    ]
    out = ROOT / "results" / "environment.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
