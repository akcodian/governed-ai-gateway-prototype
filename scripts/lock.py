"""Write requirements.lock from the current virtualenv (`pip freeze`), keeping platform-only
packages behind environment markers so the same lock installs on Windows and in Linux containers."""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

PLATFORM_ONLY = {"pywin32": 'sys_platform == "win32"', "colorama": 'sys_platform == "win32"'}
# Not installable on Windows; pinned for the Linux containers (uvicorn uses it automatically).
EXTRA_PINS = ['uvloop==0.23.0 ; sys_platform != "win32"']

out = subprocess.run([sys.executable, "-m", "pip", "freeze", "--exclude-editable"], capture_output=True, text=True,
                     check=True).stdout.splitlines()
lines = ["# Generated by scripts/lock.py from requirements.in. Python 3.12."]
for line in sorted(out, key=str.lower):
    name = line.split("==")[0].lower()
    marker = PLATFORM_ONLY.get(name)
    lines.append(f"{line} ; {marker}" if marker else line)
lines += EXTRA_PINS
Path(__file__).resolve().parents[1].joinpath("requirements.lock").write_text("\n".join(lines) + "\n")
print(f"wrote {len(lines) - 1} pins to requirements.lock")
